const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const context = {Utilities:{formatDate:(date,zone)=>new Intl.DateTimeFormat('en-US',{timeZone:zone,year:'numeric',month:'short',day:'numeric',hour:'numeric',minute:'2-digit',second:'2-digit',hour12:true,timeZoneName:'short'}).format(date)}};
vm.createContext(context);
vm.runInContext(fs.readFileSync('scripts/members-view.gs','utf8'),context);
assert.match(context.pacificSubmissionTime('2026-10-06T08:31:22.187Z'),/Oct 6, 2026.*1:31:22 AM PDT/);
assert.match(context.pacificSubmissionTime('2026-01-06T08:31:22.187Z'),/Jan 6, 2026.*12:31:22 AM PST/);
assert.match(context.pacificSubmissionTime('2026-11-01T08:30:00Z'),/1:30:00 AM PDT/);
assert.match(context.pacificSubmissionTime('2026-11-01T09:30:00Z'),/1:30:00 AM PST/);
assert.match(context.pacificSubmissionTime('2026-10-06 08:31'),/Unconfirmed timezone/);
assert.equal(context.readableMemberValue(false),'No');
assert.equal(context.readableMemberValue('No answer'),'Not answered');
const raw = [['r1','One','2026-10-06T08:31:22.187Z','full blurb',false],['r2','One','2026-10-07T08:31:22.187Z','second response',true]];
const snapshot = JSON.stringify(raw);
const result = context.memberViewRows(['ID','Full name','Submitted','About you','Wider community opt-in'],raw);
assert.equal(result.length,2,'Same name never merges separate response IDs');
assert.equal(result[0][4],'full blurb');
assert.equal(result[0][19],'No');
assert.equal(JSON.stringify(raw),snapshot,'Raw values untouched');
assert.throws(()=>context.memberViewRows(['ID','Full name'],[['','Missing']]),/Recover missing/);
assert.throws(()=>context.memberViewRows(['ID'],[['r1'],['r1']]),/Duplicate/);
console.log('PASS: original instants, Pacific DST, raw preservation, stable IDs, explicit No/unknown, no name deduplication.');
